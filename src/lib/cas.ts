// Référentiel des cas : chaque situation que l'IA d'orientation doit savoir reconnaître, avec la procédure
// à engager, la voie de recours, le délai, les diligences du devis et le modèle d'acte.
// Valeurs par défaut ci-dessous ; le référentiel en vigueur est modifiable au back office (paramètre « cas »).
// Ce module est partagé (serveur et navigateur) : aucune dépendance serveur ici.

import { z } from "zod";
import type { CodeModele } from "./modeles";
import type { CodeProcedure, Diligence } from "./procedures";

export const PROCEDURES_CAS = [
  "OQTF",
  "REFUS_TITRE",
  "REFUS_VISA",
  "NATURALISATION",
  "REFUS_IMPLICITE",
  "BLOCAGE_SIMPLE",
  "BLOCAGE_EMPLOI",
  "PROCEDURE_EN_COURS",
  "DIAGNOSTIC",
] as const satisfies readonly CodeProcedure[];

export const DILIGENCES_COMPLEMENTAIRES = ["REFERE_SUSPENSION_AVEC_REQUETE", "RECOURS_GRACIEUX"] as const satisfies readonly Diligence[];

export const MODELES_CAS = [
  "REQUETE_OQTF",
  "REQUETE_REFUS_TITRE",
  "REQUETE_SOMMAIRE",
  "MEMOIRE_COMPLEMENTAIRE",
  "REFERE_SUSPENSION",
  "REFERE_LIBERTE",
  "REFERE_MESURES_UTILES",
  "RECOURS_GRACIEUX",
  "RAPO_VISA",
  "RAPO_NATURALISATION",
  "MISE_EN_DEMEURE",
  "AVIS_ECRIT",
] as const satisfies readonly CodeModele[];

const texte = (max: number) => z.string().trim().max(max);

export const schemaCas = z.object({
  code: z.string().trim().regex(/^[A-Z0-9_]{3,40}$/, "Code : majuscules, chiffres et _ (3 à 40 caractères)."),
  /** Libellé affiché au client : la situation reconnue, en une ligne. */
  libelle: texte(160).min(5),
  /** Voie de recours affichée au client, en une ligne. */
  voieClient: texte(200).min(5),
  procedure: z.enum(PROCEDURES_CAS),
  situationOQTF: z.enum(["LIBRE", "ASSIGNE", "LIBRE_APRES_ASILE"]).nullable().default(null),
  visaType: z.enum(["COURT", "LONG"]).nullable().default(null),
  naturalisationIssue: z.enum(["REFUS", "AJOURNEMENT"]).nullable().default(null),
  /** Indices de reconnaissance, pour l'IA (mots du récit, mentions de la décision). */
  signes: texte(1500).min(10),
  /** Pour l'avocat. */
  juridiction: texte(300),
  delai: texte(400),
  /** Blocages : référé adapté. MESURES_UTILES : mise en demeure, ou référé mesures utiles si l'urgence est établie ;
   *  LIBERTE : référé-liberté d'emblée (atteinte grave et manifestement illégale à une liberté fondamentale). */
  refere: z.enum(["MESURES_UTILES", "LIBERTE"]).nullable().default(null),
  /** Blocages : la démarche engagée en préfecture (première demande, renouvellement…) est-elle demandée au client ? */
  demarche: z.boolean().default(true),
  /** Diligences ajoutées au devis, en plus de la diligence principale de la procédure. */
  complements: z.array(z.enum(DILIGENCES_COMPLEMENTAIRES)).max(2).default([]),
  modele: z.enum(MODELES_CAS),
  pieces: z.array(texte(200).min(3)).max(12).default([]),
  vigilance: z.array(texte(400).min(3)).max(10).default([]),
  actif: z.boolean().default(true),
});
export type Cas = z.infer<typeof schemaCas>;

export const schemaReferentiel = z
  .array(schemaCas)
  .min(1)
  .max(80)
  .refine((l) => new Set(l.map((c) => c.code)).size === l.length, { message: "Deux cas portent le même code." });

